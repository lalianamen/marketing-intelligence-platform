// Writes .env.local for LOCAL development from `supabase status` output.
// .env.local is git-ignored. Never commit it.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const status = JSON.parse(execSync("npx supabase status -o json", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }));
const existing = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
const keep = (name, fallback) => {
  const m = existing.match(new RegExp(`^${name}=(.*)$`, "m"));
  return m ? m[1] : fallback;
};
const lines = [
  "# Generated by `npm run env:local` for LOCAL development only. Git-ignored.",
  "APP_URL=http://127.0.0.1:3000",
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
  `DATABASE_URL=${status.DB_URL}`,
  `MAILPIT_URL=${status.MAILPIT_URL ?? status.INBUCKET_URL ?? "http://127.0.0.1:54324"}`,
  `WAREHOUSE_MODE=${keep("WAREHOUSE_MODE", "local")}`,
  `WAREHOUSE_LOCAL_URL=${status.DB_URL.replace(/\/postgres$/, "/mip_warehouse")}`,
  `DATASET_PREFIX=${keep("DATASET_PREFIX", "mip_dev")}`,
  `TOKEN_ENCRYPTION_KEY=${keep("TOKEN_ENCRYPTION_KEY", randomBytes(32).toString("base64"))}`,
  `BIGQUERY_PROJECT_ID=${keep("BIGQUERY_PROJECT_ID", "")}`,
  `BIGQUERY_LOCATION=${keep("BIGQUERY_LOCATION", "US")}`,
  `BIGQUERY_BILLING_APPROVED=${keep("BIGQUERY_BILLING_APPROVED", "false")}`,
  `BIGQUERY_MAX_BYTES_BILLED=${keep("BIGQUERY_MAX_BYTES_BILLED", "104857600")}`,
  `GOOGLE_OAUTH_CLIENT_ID=${keep("GOOGLE_OAUTH_CLIENT_ID", "")}`,
  `GOOGLE_OAUTH_CLIENT_SECRET=${keep("GOOGLE_OAUTH_CLIENT_SECRET", "")}`,
  `GOOGLE_ADS_DEVELOPER_TOKEN=${keep("GOOGLE_ADS_DEVELOPER_TOKEN", "")}`,
  `GOOGLE_ADS_LOGIN_CUSTOMER_ID=${keep("GOOGLE_ADS_LOGIN_CUSTOMER_ID", "")}`,
  `BING_OAUTH_CLIENT_ID=${keep("BING_OAUTH_CLIENT_ID", "")}`,
  `BING_OAUTH_CLIENT_SECRET=${keep("BING_OAUTH_CLIENT_SECRET", "")}`,
  `META_APP_ID=${keep("META_APP_ID", "")}`,
  `META_APP_SECRET=${keep("META_APP_SECRET", "")}`,
  "",
];
writeFileSync(".env.local", lines.join("\n"), { mode: 0o600 });
console.log("Wrote .env.local (git-ignored).");
